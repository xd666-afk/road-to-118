import { expect, test } from '@playwright/test';
import { createState } from '../../game/engine';
import { nextExperimentRound, NEXT_EXPERIMENT_SECONDS } from '../../game/experiments';
import { D } from '../../game/numbers';
import { serialize } from '../../game/save';

test('an archive commission awards a coupon and the next industry upgrade uses it', async ({ page }) => {
  const now = Date.now();
  const state = createState(233, now);
  state.settings.guideDismissed = true;
  state.settings.reducedMotion = true;
  for (const row of state.elements.slice(0, 7)) row.discovered = true;
  state.coins = D(10_000);
  state.data = D(10_000);
  state.reactors[0].target = 1;
  state.reactors[1].built = true;
  state.reactors[1].target = 2;
  state.modules.feed = true;
  state.experimentBoard = nextExperimentRound(state, 1, false);
  const offer = state.experimentBoard.offers[2];
  if (offer.kind !== 'archive') throw new Error('Missing archive offer');
  const specimen = state.elements[offer.z - 1];
  specimen.inventory = D(offer.goal);
  specimen.totalProduced = D(offer.goal);
  await page.clock.install({ time: now });
  await page.clock.pauseAt(now + 1000);
  await page.addInitScript(text => {
    const key = 'road-to-118.save.v1';
    if (!localStorage.getItem(key)) localStorage.setItem(key, text);
  }, serialize(state, now + 1000));
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto('/');
  const board = page.locator('.experiment-board');
  await board.locator('summary').click();
  await expect(board.getByRole('button', { name: /手动碰撞/ })).toBeVisible();
  await expect(board.getByRole('button', { name: /仪器生产/ })).toBeVisible();
  await board.getByRole('button', { name: /工业升级费用减免 25%/ }).click();
  await expect(board).toContainText('剩余 120 秒');
  await board.getByRole('button', { name: '打开元素档案' }).click();
  await page.getByRole('dialog').getByRole('button', { name: /提交.*单位至档案/ }).click();
  await page.getByRole('button', { name: '关闭弹窗' }).click();
  await board.getByRole('button', { name: '领取奖励' }).click();
  await expect(board).toContainText('持有工业升级券');
  await page.clock.runFor((NEXT_EXPERIMENT_SECONDS + 1) * 1000);
  await expect(board).toContainText('第 2 轮');
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '科研' }).click();
  const feed = page.getByRole('region', { name: '原料补充' });
  await expect(feed).toContainText('减免 25%');
  await feed.getByRole('button', { name: '升级至 2 级' }).click();
  await expect(feed).toContainText('等级 2 / 3');
  await expect(feed).not.toContainText('已应用工业升级券');
});
